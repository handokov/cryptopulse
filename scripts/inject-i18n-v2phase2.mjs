function serialize(obj, indent) {
  const pad = " ".repeat(indent);
  return Object.entries(obj)
    .map(([k, v]) => `${pad}${k}: ${JSON.stringify(v)},`)
    .join("\n");
}

for (const [lang, keys] of Object.entries(KEYS)) {
  const file = `${DIR}${lang}.ts`;
  let src = readFileSync(file, "utf8");
  if (src.includes("chartDragHint:")) {
    console.log(`${lang}: already injected, skip`);
    continue;
  }
  const botStart = src.indexOf("  bot: {");
  if (botStart < 0) throw new Error(`${lang}: bot namespace not found`);
  const closeIdx = src.indexOf("\n  },", botStart);
  if (closeIdx < 0) throw new Error(`${lang}: bot namespace close not found`);
  const insertion = `\n${serialize(keys, 4)}`;
  src = src.slice(0, closeIdx) + insertion + src.slice(closeIdx);
  writeFileSync(file, src);
  console.log(`${lang}: injected ${Object.keys(keys).length} keys`);
}
